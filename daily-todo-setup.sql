-- English Hub Daily To-Do tables
create table if not exists public.daily_tasks (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  task_text text not null check (length(trim(task_text)) > 0 and length(task_text) <= 160),
  created_at timestamptz not null default now()
);
create table if not exists public.daily_task_completions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  task_id bigint not null references public.daily_tasks(id) on delete cascade,
  task_date date not null,
  created_at timestamptz not null default now(),
  unique (user_id, task_id, task_date)
);
alter table public.daily_tasks enable row level security;
alter table public.daily_task_completions enable row level security;
drop policy if exists "Users manage own daily tasks" on public.daily_tasks;
create policy "Users manage own daily tasks" on public.daily_tasks for all using (auth.uid() = user_id) with check (auth.uid() = user_id);
drop policy if exists "Users manage own task completions" on public.daily_task_completions;
create policy "Users manage own task completions" on public.daily_task_completions for all using (auth.uid() = user_id) with check (auth.uid() = user_id);
